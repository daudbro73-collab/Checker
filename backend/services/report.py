from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas
from reportlab.lib import colors

def create_pdf_report(filename, data):
    c = canvas.Canvas(filename, pagesize=letter)
    width, height = letter
    
    # Header
    c.setFont("Helvetica-Bold", 24)
    c.drawString(50, height - 50, "AML Compliance Report")
    
    c.setFont("Helvetica", 12)
    c.drawString(50, height - 80, f"Generated for: {data['address']}")
    c.drawString(50, height - 100, f"Date: 2024-05-23") # Mock date
    
    # Risk Score
    score = data['risk_score']
    c.setFont("Helvetica-Bold", 18)
    if score > 75:
        c.setFillColor(colors.red)
        risk_text = "HIGH RISK"
    else:
        c.setFillColor(colors.green)
        risk_text = "LOW RISK"
        
    c.drawString(50, height - 150, f"Risk Score: {score}/100 ({risk_text})")
    c.setFillColor(colors.black)
    
    # Details
    c.setFont("Helvetica", 14)
    c.drawString(50, height - 200, "Detailed Analysis:")
    
    y = height - 230
    sanctions = data['sanctions']
    
    c.setFont("Helvetica", 12)
    c.drawString(70, y, f"Sanctions List Check: {'MATCH FOUND' if sanctions['is_sanctioned'] else 'CLEAN'}")
    y -= 20
    if sanctions['is_sanctioned']:
        c.drawString(70, y, f"Source: {sanctions['source']}")
        y -= 20
        c.drawString(70, y, f"Reason: {sanctions['reason']}")
        y -= 20

    # On-Chain Data
    chain_data = data.get('chain_data', {})
    c.drawString(70, y, f"Network: {data.get('chain', 'ETH')}")
    y -= 20
    c.drawString(70, y, f"Balance: {chain_data.get('balance_display', chain_data.get('balance', 'N/A'))}")
    y -= 20
    c.drawString(70, y, f"Transactions: {chain_data.get('tx_count', 'N/A')}")
    y -= 20

    # Risk Factors Breakdown
    factors = data.get('risk_factors', [])
    if factors:
        y -= 20
        c.setFont("Helvetica-Bold", 14)
        c.drawString(50, y, "Risk Factors Identified:")
        y -= 25
        c.setFont("Helvetica", 12)
        c.setFillColor(colors.red)
        for f in factors:
            c.drawString(70, y, f"• [{f['level']}] {f['desc']}")
            y -= 20
        c.setFillColor(colors.black)

    # Disclaimer
    c.setFont("Helvetica-Oblique", 8)
    c.setFillColor(colors.gray)
    c.drawString(50, 80, "Disclaimer: This report is generated by an automated system for informational purposes only.")
    c.drawString(50, 70, "It does not constitute legal or financial advice. Data provided by public sources.")
    
    # Footer
    c.setFont("Helvetica-Oblique", 10)
    c.setFillColor(colors.black)
    c.drawString(50, 50, "Generated by Professional AML Service")
    
    c.save()
