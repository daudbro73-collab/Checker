from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas
from reportlab.lib import colors
from reportlab.graphics.shapes import Drawing, Rect, String
from reportlab.graphics import renderPDF

def draw_header(c, width, height):
    # Dark Header Background
    c.setFillColorRGB(0.05, 0.1, 0.2) # Dark Blue
    c.rect(0, height - 100, width, 100, fill=1, stroke=0)
    
    # Logo (Text for now)
    c.setFillColor(colors.white)
    c.setFont("Helvetica-Bold", 30)
    c.drawString(50, height - 60, "AML GUARDIAN")
    
    c.setFont("Helvetica", 10)
    c.drawString(50, height - 80, "Premium Blockchain Intelligence")

def create_premium_pdf(filename, data):
    c = canvas.Canvas(filename, pagesize=A4)
    width, height = A4
    
    draw_header(c, width, height)
    
    # Report Meta
    c.setFillColor(colors.black)
    c.setFont("Helvetica-Bold", 16)
    c.drawString(50, height - 150, "Compliance Report")
    
    c.setFont("Helvetica", 10)
    c.setFillColor(colors.gray)
    c.drawString(50, height - 170, f"Generated: 2024-05-23 | ID: #AML-{data['address'][:6]}")
    
    # Risk Score Card
    score = data['risk_score']
    c.setStrokeColor(colors.lightgrey)
    c.rect(50, height - 280, 250, 80, fill=0, stroke=1) # Box
    
    c.setFont("Helvetica-Bold", 12)
    c.setFillColor(colors.black)
    c.drawString(70, height - 220, "RISK SCORE")
    
    c.setFont("Helvetica-Bold", 40)
    if score > 75:
        c.setFillColor(colors.red)
        risk_text = "CRITICAL"
    elif score > 40:
        c.setFillColor(colors.orange)
        risk_text = "WARNING"
    else:
        c.setFillColor(colors.green)
        risk_text = "SAFE"
        
    c.drawString(70, height - 260, f"{score}/100")
    
    c.setFont("Helvetica-Bold", 14)
    c.drawString(180, height - 260, risk_text)

    # Wallet Details
    y = height - 320
    c.setFont("Helvetica-Bold", 14)
    c.setFillColor(colors.black)
    c.drawString(50, y, "Wallet Analysis")
    y -= 20
    
    c.setFont("Helvetica", 11)
    c.drawString(50, y, f"Address: {data['address']}")
    y -= 15
    c.drawString(50, y, f"Network: {data.get('chain', 'Unknown')}")
    
    # Chain Data
    chain_data = data.get('chain_data', {})
    y -= 30
    c.drawString(50, y, f"Balance: {chain_data.get('balance_display', 'N/A')}")
    if 'usdt_balance' in chain_data:
         y -= 15
         c.drawString(50, y, f"USDT Balance: {chain_data['usdt_balance']}")
         
    y -= 15
    c.drawString(50, y, f"Total Transactions: {chain_data.get('tx_count', 0)}")
    
    # Risk Factors
    y -= 40
    factors = data.get('risk_factors', [])
    if factors:
        c.setFont("Helvetica-Bold", 14)
        c.drawString(50, y, "Risk Factors Identified")
        y -= 10
        c.setStrokeColor(colors.red)
        c.line(50, y, 200, y)
        y -= 20
        
        c.setFont("Helvetica", 10)
        c.setFillColor(colors.red)
        for f in factors:
            c.drawString(60, y, f"• [{f['level']}] {f['desc']}")
            y -= 15
    else:
        c.setFont("Helvetica", 10)
        c.setFillColor(colors.green)
        c.drawString(50, y, "No significant risk factors identified.")

    # QR Code Placeholder (Box)
    c.setStrokeColor(colors.black)
    c.rect(width - 150, height - 250, 100, 100)
    c.setFont("Helvetica", 8)
    c.setFillColor(colors.black)
    c.drawString(width - 145, height - 265, "Scan to verify report")
    
    # Footer
    c.setFont("Helvetica-Oblique", 8)
    c.setFillColor(colors.gray)
    c.drawString(50, 50, "CONFIDENTIAL - For Internal Compliance Use Only. Generated by AML Guardian.")
    
    c.save()
